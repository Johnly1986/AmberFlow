import { chromium } from "playwright";
import * as be from "../src/browser-env.ts";
import { extractElements, urlOf } from "../src/extraction.ts";
import { induceSignals } from "../src/signal-induction.ts";
import { evalSignalOnState } from "../src/signals.ts";
const b: any = await be.launch({ chromium } as never, true);
const page = await b.newPage();
await page.goto(`file://${process.cwd()}/testpages/product.html`, { waitUntil: "domcontentloaded" });
const snap = async () => ({ url: urlOf(page as never), elems: await extractElements(page as never) });
const before = await snap();
await page.click("[data-test=add-to-cart]");
const after = await snap();
console.log("before pool:", Object.entries(before.elems).map(([r, e]: any) => `${r}:${e.tag}[${e.data_test}]"${e.label}"`).join(" "));
console.log("after  pool:", Object.entries(after.elems).map(([r, e]: any) => `${r}:${e.tag}[${e.data_test}]"${e.label}"`).join(" "));
const r = induceSignals(before, after);
console.log("verdict:", r.verdict, "| effect:", r.effect);
for (const c of r.candidates) console.log("  ", c.kind, JSON.stringify(c.signal), "|", c.why);
console.log("rejected:", r.rejected.map((x) => `${JSON.stringify(x.signal)} (${x.reason})`).join(" ; "));
console.log("eval cart-count=1 before/after:", evalSignalOnState({ css_text_equals: ["[data-test=cart-count]", "1"] }, before), evalSignalOnState({ css_text_equals: ["[data-test=cart-count]", "1"] }, after));
await b.close();
